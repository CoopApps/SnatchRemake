/** Draw uppercase text at (x, y). Character cell is 6x8 (5-wide glyph + 1 gap). */
export function drawText(screen: Screen, x: number, y: number, s: string, colour: Rgb): void {
  let cx = x;
  for (const ch of s.toUpperCase()) {
    const g = GLYPHS[ch] ?? GLYPHS[' '];
    for (let py = 0; py < g.length; py++) for (let px = 0; px < g[py].length; px++) {
      if (g[py][px] === '1') screen.fillRect(cx + px, y + py, 1, 1, colour);
    }
    cx += 6;
  }
}

/** Width in pixels of a string rendered with drawText. */
export function textWidth(s: string): number { return s.length * 6 - 1; }
